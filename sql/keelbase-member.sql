-- 模块：member。本模块的页面与工具面所读的表。
--
-- 来源分两半。上游给这个模块的测试 schema（`yudao-module-member/src/test/resources/sql/create_tables.sql`）
-- 覆盖 5 张：`member_user` / `member_address` / `member_tag` / `member_level` / `member_group`。其余 6 张
-- （`member_config` / `member_point_record` / `member_sign_in_config` / `member_sign_in_record` /
-- `member_level_record` / `member_experience_record`）那份 schema 没写，照 `keelbase-crm.sql` 的办法从各自的
-- 数据对象推导。
--
-- 那份 schema 里的 `member_brokerage_record` **不建**：模块里没有对应的数据对象（上游已移除分销），
-- 建它只是一张没人读的表。凡「有 DO 而 schema 没写」都建、凡「schema 写了而没 DO」都不建。
--
-- 方言转换只做方言层：`tinyint`→`int2`、`bit`→`boolean`（`deleted` 除外，宿主把它当数字比）、
-- `datetime`→`timestamp`、自增列用 `GENERATED BY DEFAULT AS IDENTITY`。不动任何业务语义。
--
-- **每张表都带 `tenant_id`。** 本部署的 `yudao.tenant.ignore-tables` 是空的，租户拦截器对**每一张表**都加
-- 条件——真栈实测过：`member_point_record` 少这一列时，查询以 `column "tenant_id" does not exist` 失败。
-- 上游测试 schema 里 `member_address` 与 `member_tag` 没有这一列，这里按本宿主的要求补上。
--
-- 每张表的主键序列取自它自己数据对象上的 `@KeySequence`——本模块恰好都是 `member_<表名>_seq`。
--
-- 幂等：每条语句都是 `create … if not exists`。
--
-- Module: member. The tables this module's pages and tool faces read.
--
-- Two halves. Upstream's own test schema for the module
-- (`yudao-module-member/src/test/resources/sql/create_tables.sql`) covers five: `member_user`,
-- `member_address`, `member_tag`, `member_level`, `member_group`. The other six (`member_config`,
-- `member_point_record`, `member_sign_in_config`, `member_sign_in_record`, `member_level_record`,
-- `member_experience_record`) are derived from their data objects, the way `keelbase-crm.sql` was.
--
-- The test schema's `member_brokerage_record` is **not** created: the module has no data object for it
-- (upstream removed the distribution feature), and creating it would leave a table nobody reads. The rule
-- is "a table exists when a data object declares it" in both directions.
--
-- The conversion is dialect only: `tinyint` to `int2`, `bit` to `boolean` (except `deleted`, which the
-- host compares as a number), `datetime` to `timestamp`, and the auto-increment column.
--
-- **Every table carries `tenant_id`.** This deployment's `yudao.tenant.ignore-tables` is empty, so the
-- tenant interceptor adds a condition to every table — measured on the real stack: `member_point_record`
-- without that column failed with `column "tenant_id" does not exist`. Two tables in upstream's test
-- schema lack it; they get it here.
--
-- Each table's key sequence comes from its own data object's `@KeySequence` — in this module they all
-- happen to be `member_<table>_seq`.
--
-- Idempotent: every statement is `create … if not exists`.

create sequence if not exists member_user_seq;
create sequence if not exists member_address_seq;
create sequence if not exists member_tag_seq;
create sequence if not exists member_level_seq;
create sequence if not exists member_group_seq;
create sequence if not exists member_config_seq;
create sequence if not exists member_point_record_seq;
create sequence if not exists member_sign_in_config_seq;
create sequence if not exists member_sign_in_record_seq;
create sequence if not exists member_level_record_seq;
create sequence if not exists member_experience_record_seq;

CREATE TABLE IF NOT EXISTS member_user (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    mobile varchar(11) NOT NULL,
    email varchar(50) DEFAULT NULL,
    password varchar(100) NOT NULL DEFAULT '',
    status int2 NOT NULL DEFAULT 0,
    register_ip varchar(50) DEFAULT NULL,
    register_terminal int DEFAULT NULL,
    login_ip varchar(50) DEFAULT '',
    login_date timestamp DEFAULT NULL,
    nickname varchar(30) NOT NULL DEFAULT '',
    avatar varchar(512) NOT NULL DEFAULT '',
    name varchar(30) DEFAULT NULL,
    sex int2 DEFAULT 0,
    birthday timestamp DEFAULT NULL,
    area_id int DEFAULT NULL,
    mark varchar(255) DEFAULT NULL,
    point int NOT NULL DEFAULT 0,
    tag_ids varchar(255) DEFAULT NULL,
    level_id bigint DEFAULT NULL,
    experience int DEFAULT NULL,
    group_id bigint DEFAULT NULL,
    creator varchar(64) DEFAULT '',
    create_time timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updater varchar(64) DEFAULT '',
    update_time timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted int2 NOT NULL DEFAULT 0,
    tenant_id bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (id)
);

